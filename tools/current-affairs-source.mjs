// Current-affairs question generation for FactFlow.
//
// The app is static and has no backend, so this runs inside the scheduled
// GitHub Action and commits its output into the corpus. Questions are built
// from date-qualified Wikidata statements rather than from prose, so the
// generated answer is always traceable to a structured fact.

const WIKIDATA_ENDPOINTS = [
  'https://qlever.dev/api/wikidata',
  'https://query.wikidata.org/sparql'
];
export const CURRENT_AFFAIRS_SOURCE_VERSION = 1;

const MONTHS = ['January', 'February', 'March', 'April', 'May', 'June',
  'July', 'August', 'September', 'October', 'November', 'December'];

function hash(value) {
  let result = 2166136261;
  for (const character of String(value)) {
    result ^= character.codePointAt(0);
    result = Math.imul(result, 16777619);
  }
  return result >>> 0;
}

function normalized(value) {
  return String(value || '').normalize('NFKC').toLowerCase().replace(/[^\p{L}\p{N}]+/gu, '');
}

