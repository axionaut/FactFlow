function rowsFrom(bindings) {
  return bindings.map((binding) => ({
    itemId: entityId(binding.item?.value),
    itemUrl: binding.item?.value || '',
    itemLabel: String(binding.itemLabel?.value || '').trim(),
    subjectId: entityId(binding.subject?.value),
    subjectLabel: String(binding.subjectLabel?.value || '').trim(),
    start: String(binding.start?.value || '')
  })).filter((row) => row.itemId && row.subjectId
    && row.itemLabel.length >= 2 && row.itemLabel.length <= 80
    && row.subjectLabel.length >= 2 && row.subjectLabel.length <= 90
    && !hasBrokenEncoding(row.itemLabel)
    && !hasBrokenEncoding(row.subjectLabel)
    && !/^Q\d+$/.test(row.itemLabel));
}

function whenLabel(start) {
  const date = new Date(start);
  if (Number.isNaN(date.getTime())) return '';
  return `${MONTHS[date.getUTCMonth()]} ${date.getUTCFullYear()}`;
}

export function buildCurrentAffairsQuestions(profile, bindings, accessedAt = new Date().toISOString().slice(0, 10)) {
  const rows = rowsFrom(bindings);
  const bySubject = new Map();
  for (const row of rows) {
    if (!bySubject.has(row.subjectId)) bySubject.set(row.subjectId, []);
    bySubject.get(row.subjectId).push(row);
  }
  // A subject with several concurrent claimants is ambiguous as a lookup, so
  // lookup profiles keep only subjects with a single recorded holder.
  const usable = profile.membership
    ? rows
    : [...bySubject.values()]
      .filter((group) => new Set(group.map((row) => normalized(row.itemLabel))).size === 1)
      .map((group) => group[0]);

  const peoplePool = [...new Map(rows.map((row) => [normalized(row.itemLabel), row.itemLabel])).values()];
  if (peoplePool.length < 4) return [];

  const seen = new Set();
  return usable.flatMap((row) => {
    const key = profile.membership ? `${row.subjectId}:${row.itemId}` : row.subjectId;
    if (seen.has(key)) return [];
    seen.add(key);
    const year = new Date(row.start).getUTCFullYear();
    // Foils must not themselves be correct answers for this same subject.
    const sameSubject = new Set((bySubject.get(row.subjectId) || []).map((entry) => normalized(entry.itemLabel)));
    const eligible = peoplePool.filter((person) => !sameSubject.has(normalized(person)));
    if (eligible.length < 3) return [];
    const ordered = rotate(eligible, hash(`${profile.id}:${row.itemId}`) % eligible.length);
    const distractors = ordered.slice(0, 3);
    if (distractors.length !== 3) return [];
    const correctSlot = hash(`${row.itemId}:${row.subjectId}:slot`) % 4;
    const options = [...distractors];
    options.splice(correctSlot, 0, row.itemLabel);
    const canonicalKey = `ca-${profile.id}-${row.subjectId}-${row.itemId}`;
    return [{
      id: canonicalKey,
      canonical_key: canonicalKey,
      season: null,
      episode: null,
      air_date: null,
      question_text: profile.membership
        ? profile.question(row.subjectLabel, year)
        : profile.question(row.subjectLabel),
      options,
      correct_option_index: correctSlot,
      question_type: 'practice',
      category: profile.category,
      subcategory: profile.id,
      question_shape: profile.membership ? 'membership' : 'lookup',
      difficulty_tier: profile.tier,
      prize_level_asked_at: null,
      source: 'Wikidata current affairs',
      source_schema_version: CURRENT_AFFAIRS_SOURCE_VERSION,
      source_url: row.itemUrl,
      source_accessed_at: accessedAt,
      // Drives recency weighting in question selection.
      event_date: row.start.slice(0, 10),
      tags: profile.tags,
      language_original: 'en',
      translation_status: 'not required',
      explanation: profile.explanation(row.itemLabel, row.subjectLabel, whenLabel(row.start)),
      provenance_status: 'Date-qualified Wikidata statement; current as of the corpus refresh date'
    }];
  });
}

async function runQuery(query, label) {
  const errors = [];
  for (const endpoint of WIKIDATA_ENDPOINTS) {
    try {
      const url = `${endpoint}?query=${encodeURIComponent(query)}&format=json`;
      const response = await fetch(url, {
        headers: {
          accept: 'application/sparql-results+json',
          'user-agent': 'FactFlow/38 (+https://github.com/axionaut/FactFlow)'
        },
        signal: AbortSignal.timeout(40000)
      });
      if (!response.ok) throw new Error(`${response.status}`);
      const payload = await response.json();
      return Array.isArray(payload?.results?.bindings) ? payload.results.bindings : [];
    } catch (error) {
      errors.push(`${new URL(endpoint).hostname}: ${error.message}`);
    }
  }
  throw new Error(`Current affairs ${label} failed (${errors.join(', ')})`);
}

export async function gatherCurrentAffairsQuestions(options = {}) {
  const now = options.now || new Date();
  const limit = Math.max(20, Number(options.limit || 120));
  const questions = [];
  const errors = [];
  for (const profile of currentAffairsProfiles(now)) {
    try {
      const bindings = await runQuery(`${profile.query}\nLIMIT ${limit}`, profile.id);
      questions.push(...buildCurrentAffairsQuestions(profile, bindings));
    } catch (error) {
      errors.push(error.message);
    }
  }
  return { questions, errors, generated_at: now.toISOString() };
}
